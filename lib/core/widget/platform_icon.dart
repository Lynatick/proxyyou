    super.textDirection,
    super.applyTextScaling,
    super.blendMode,
    super.fontWeight,
  });

  static IconData? resolve(IconData? icon, TargetPlatform platform) =>
      platform == TargetPlatform.windows ? _windows[icon] ?? icon : icon;

  @override
  Widget build(BuildContext context) {
    final glyph = resolve(icon, Theme.of(context).platform);
    if (glyph == icon) return super.build(context);
    return Icon(
      glyph,
      size: size,
      fill: fill,
      weight: weight,
      grade: grade,
      opticalSize: opticalSize,
      color: color,
      shadows: shadows,
      semanticLabel: semanticLabel,
      textDirection: textDirection,
      applyTextScaling: applyTextScaling,
      blendMode: blendMode,
      fontWeight: fontWeight,
    ).build(context);
  }

